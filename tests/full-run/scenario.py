@dataclass
class Scenario:
    """Уникальные для запуска идентификаторы.

    `reference` и `wb_order_id` — ключи идемпотентности (инвариант 5), поэтому
    в пределах одного запуска они не повторяются, а между запусками не
    сталкиваются: иначе второй прогон за день упрётся в собственный вчерашний
    документ и покраснеет не по делу.
    """

    run_id: str = field(default_factory=lambda: time.strftime("%Y%m%d-%H%M%S"))
    order_base: int = field(default_factory=lambda: int(time.time()) * 1000)
    _order_seq: int = 0
    _lock: threading.Lock = field(default_factory=threading.Lock)

    def reference(self, name: str) -> str:
        return f"FR-{self.run_id}-{name}"

    def next_order_id(self) -> int:
        # Под замком: нагрузочный шаг зовёт этот счётчик из восьми потоков, а
        # два одинаковых wb_order_id дадут «отказ» там, где виноват прогон.
        with self._lock:
            self._order_seq += 1
            return self.order_base + self._order_seq

    def idem(self, name: str) -> str:
        return f"idem-{self.run_id}-{name}"
