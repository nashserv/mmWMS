#!/usr/bin/env bash
# Проверка перед подъёмом боевого контура. Шаги 4–6 раздела 11.
#
# Стендовые ворота (`check-no-live-tokens.sh`) проверяют, что живого токена
# НЕТ. Здесь всё наоборот: токен обязан быть, кабинет обязан быть ровно один,
# режим обязан быть `live`. Запускать стендовые ворота на бою нельзя — они не
# дали бы контуру подняться вовсе.
#
# Каждая проверка отвечает на вопрос «что сломается, если этого не сделать»,
# а не «красиво ли настроено».
#
# Код возврата: 0 — можно поднимать, 1 — нельзя.

set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
FAILED=0

bad() { echo "  НЕТ: $*" >&2; FAILED=1; }
ok()  { echo "  да: $*"; }

echo "преflight боевого контура"

# shellcheck disable=SC1091
if [ -f "${HERE}/.env" ]; then set -a; . "${HERE}/.env"; set +a; else
    echo "  НЕТ: ${HERE}/.env отсутствует. Боевой контур не поднимается на умолчаниях." >&2
    exit 1
fi

# --- 1. Разрешение владельца на этот шаг ------------------------------------
#
# Не техническая проверка, а напоминание с подписью. Раздел 12 требует явного
# разрешения на КАЖДОЕ изменение боевого контура, и «я думал, мы договорились»
# — не разрешение.
if [ -z "${PROD_OWNER_APPROVAL:-}" ]; then
    bad "PROD_OWNER_APPROVAL пуст. Впишите туда, на какой шаг и какой кабинет"
    echo "      получено разрешение владельца и когда. Без этого контур не поднимается." >&2
else
    ok "разрешение владельца: ${PROD_OWNER_APPROVAL}"
fi

# --- 2. Ровно один кабинет --------------------------------------------------
#
# Раздел 11 требует переключать по одному, не пачкой. Список через запятую на
# шаге 4 означает, что кто-то решил ускориться.
accounts="${PROD_WB_ACCOUNTS:-}"
if [ -z "$accounts" ]; then
    bad "PROD_WB_ACCOUNTS пуст — это «все кабинеты сразу»"
elif printf '%s' "$accounts" | grep -q ','; then
    bad "PROD_WB_ACCOUNTS содержит несколько кабинетов: ${accounts}"
    echo "      Раздел 11: по одному, не пачкой, и разрешение на каждый отдельно." >&2
else
    ok "кабинет ровно один: ${accounts}"
fi

# --- 3. Настоящий Wildberries, а не пустой адрес ----------------------------
#
# С пустым WB_API_URL сервис считает, что рядом симулятор. Это единственная
# дорога, которой можно писать не туда, думая, что пишешь в песочницу.
case "${WB_API_URL:-}" in
    https://*) ok "адрес Wildberries: ${WB_API_URL}" ;;
    "")        bad "WB_API_URL пуст — сервис сочтёт, что рядом симулятор" ;;
    *)         bad "WB_API_URL не https: ${WB_API_URL}" ;;
esac

# --- 4. Токен кабинета лежит файлом -----------------------------------------
#
# Значение токена не появляется в переменных никогда (инвариант 15). Файл
# обязан существовать и быть непустым: пустой файл — это 401 и полдня поисков.
dir="${WB_SECRET_HOST_DIR:-}"
if [ -z "$dir" ] || [ ! -d "$dir" ]; then
    bad "каталога секретов ${dir:-<пусто>} нет"
else
    found="$(find "$dir" -type f -size +0c 2>/dev/null | wc -l)"
    if [ "$found" -eq 0 ]; then
        bad "в ${dir} нет ни одного непустого файла секрета"
    else
        ok "секретов в ${dir}: ${found}"
    fi
    # Права: секрет, доступный на чтение всем, — это секрет ровно до первого
    # любопытного на машине.
    loose="$(find "$dir" -type f -perm /0044 2>/dev/null | wc -l)"
    [ "$loose" -gt 0 ] && bad "секретов с правами на чтение для всех: ${loose} (нужен umask 077)"
fi

# --- 5. Частота опроса посчитана, а не выдумана -----------------------------
#
# У кабинета 300 запросов в минуту ВСЕГО, и боевой шлюз уже их тратит.
# Упереться в лимит из-за нас — значит лишить клиента его же заданий.
if [ -z "${PROD_POLL_INTERVAL_SECONDS:-}" ]; then
    bad "PROD_POLL_INTERVAL_SECONDS пуст (вопрос 11 раздела 13 — сколько тратит бой)"
    echo "      Считает: infrastructure/shadow/scripts/poll-budget.py --prod-rpm N" >&2
else
    ok "интервал опроса: ${PROD_POLL_INTERVAL_SECONDS} с"
fi

# --- 6. Формат этикетки подтверждён -----------------------------------------
#
# Вопрос 2 раздела 13. К шагу 5 обязан быть закрыт: принтер, не понявший ZPL,
# печатает пустое, а задание считается сдвинутым.
if [ -z "${WB_STICKER_FORMAT:-}" ]; then
    bad "WB_STICKER_FORMAT пуст"
elif [ -z "${PROD_PRINTER_CONFIRMED:-}" ]; then
    bad "PROD_PRINTER_CONFIRMED пуст: формат ${WB_STICKER_FORMAT} не проверен на живом принтере"
    echo "      На шаге 4 стикеры не запрашиваются — можно поставить «шаг 4, не требуется»." >&2
else
    ok "этикетка ${WB_STICKER_FORMAT}, проверка принтера: ${PROD_PRINTER_CONFIRMED}"
fi

# --- 7. Каталог бэкапов существует и доступен на запись ---------------------
#
# Бэкап, которому некуда писать, молчит об этом ровно до дня аварии.
backups="${PROD_BACKUP_DIR:-}"
if [ -z "$backups" ] || [ ! -d "$backups" ]; then
    bad "каталога бэкапов ${backups:-<пусто>} нет"
elif [ ! -w "$backups" ]; then
    bad "в ${backups} нельзя писать"
else
    ok "бэкапы: ${backups}"
fi

# --- 8. Дежурному есть куда позвонить ---------------------------------------
if [ -z "${ALERTMANAGER_WEBHOOK:-}" ]; then
    bad "ALERTMANAGER_WEBHOOK пуст — алерты будут срабатывать в пустоту"
else
    ok "приёмник алертов задан"
fi

# --- 9. Секреты не совпадают между собой ------------------------------------
#
# Одинаковые пароли у шести ролей означают, что разделение ролей — это
# переименование: утёк один — открыты все.
same="$(printf '%s\n' "${SERVICE_DB_PASSWORD_WMS:-1}" "${SERVICE_DB_PASSWORD_BILLING:-2}" \
        "${SERVICE_DB_PASSWORD_IDENTITY:-3}" "${SERVICE_DB_PASSWORD_PORTAL:-4}" \
        "${SERVICE_DB_PASSWORD_ADMIN:-5}" "${SERVICE_DB_PASSWORD_WORKSTATION:-6}" \
        | sort -u | wc -l)"
if [ "$same" -lt 6 ]; then
    bad "пароли ролей повторяются (различных: ${same} из 6) — разделение ролей мнимое"
else
    ok "у каждой роли свой пароль"
fi

# --- 10. Стендовых ворот здесь нет ------------------------------------------
#
# Проверка от обратного: если кто-то скопировал стендовый compose целиком,
# сюда приедет token-guard, и контур не поднимется вовсе — а причину будут
# искать в сети.
# Комментарии отрезаются: в шапке compose объясняется, ПОЧЕМУ этих ворот тут
# нет, и ловить собственное объяснение — это проверка, которая всегда красная.
if sed 's/#.*//' "${HERE}/compose.prod.yaml" 2>/dev/null | grep -q 'check-no-live-tokens'; then
    bad "в compose.prod.yaml есть token-guard: стендовые ворота на бою запрещают живой токен"
else
    ok "стендовых ворот в контуре нет"
fi

echo
if [ "$FAILED" -ne 0 ]; then
    echo "ПОДНИМАТЬ НЕЛЬЗЯ" >&2
    exit 1
fi
echo "можно поднимать: docker compose -f compose.prod.yaml up -d"
