#!/usr/bin/env bash
# Откат боевого контура. Раздел 11: «вернуть кабинет боевому шлюзу».
#
# Откат на шагах 4–6 НЕ бесплатный, в отличие от шага 2. На шаге 2 мы ничего не
# писали, и остановить контур было достаточно. Здесь мы уже писали в кабинет:
# публиковали остатки (шаг 4), запрашивали стикеры и собирали поставки (шаг 5).
#
# Что делает откат и чего не делает:
#
#   * ОСТАНАВЛИВАЕТ запись в Wildberries первым же действием — до всего
#     остального. Пока воркеры живы, они продолжают публиковать остатки, и
#     каждая секунда промедления — это ещё одно расхождение с боевым шлюзом,
#     который вот-вот заберёт кабинет обратно.
#   * НЕ трогает данные. Том остаётся: движения, задания, начисления — это
#     факты о том, что физически произошло на складе, и они нужны, чтобы
#     разобрать причину отката.
#   * НЕ мигрирует данные обратно в Odoo. Раздел 11: боевой контур всё время
#     оставался актуальным, возвращать в него нечего.
#
# После отката кабинет обязан быть возвращён боевому шлюзу ВРУЧНУЮ — это
# изменение боевого контура, и разрешение владельца нужно на него отдельно.

set -euo pipefail
cd "$(dirname "$0")"

echo "ОТКАТ боевого контура"
echo

# 1. Сначала — заткнуть запись. Порядок здесь важнее аккуратности: каждая
#    секунда работающего опросчика добавляет расхождение.
echo "1/3 останавливаю всё, что пишет в Wildberries"
docker compose -f compose.prod.yaml stop \
    wms-wb-sync wms-wb-labels wms-wb-reconcile wms-outbox || true

# 2. Потом — приём новой работы. Маршруты гасим после воркеров: пока они живы,
#    остановленный API ничего не меняет, а оператор у стойки хотя бы видит
#    отказ, а не пустой экран.
echo "2/3 останавливаю приём работы"
docker compose -f compose.prod.yaml stop wms workstation || true

# 3. Остальное — в свой срок. Биллинг и портал гасим последними: они никому не
#    пишут в WB, зато по ним разбирают, что успело начислиться.
echo "3/3 останавливаю остальное"
docker compose -f compose.prod.yaml stop || true

cat <<'ТЕКСТ'

Контур остановлен. Данные на месте — том не удалён.

ДАЛЬШЕ ВРУЧНУЮ, и это требует отдельного разрешения владельца (раздел 12):

  1. Вернуть кабинет боевому шлюзу: включить его в старом контуре.
  2. Сверить остатки. Мы публиковали их в кабинет; боевой шлюз опубликует свои.
     Разойтись они могут ровно на то, что успело уехать между последней нашей
     публикацией и первой его.
  3. Разобрать, что осталось в поставках. Незакрытая поставка на стороне WB —
     это задания, которые ни один из контуров не считает своими.

Данные удаляются только осознанно и только после разбора:
    docker compose -f compose.prod.yaml down -v
ТЕКСТ
