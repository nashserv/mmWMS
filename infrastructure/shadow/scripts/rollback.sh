#!/usr/bin/env bash
# Откат shadow. Раздел 11: «Откат на любом шаге: вернуть кабинет боевому шлюзу».
#
# На шаге 2 откат дешёвый до неприличия — shadow ничего не писала, возвращать
# нечего. Останавливаем контур, и всё: боевой шлюз как работал с кабинетом,
# так и работает, он о нас не знал.
#
# Данные НЕ удаляются: том `shadow-postgres` остаётся. Отчёт расхождений за
# наблюдавшуюся неделю — единственный результат шага 2, и терять его при
# откате нельзя. Чтобы удалить осознанно: docker compose ... down -v
#
set -euo pipefail
cd "$(dirname "$0")/.."

echo "Останавливаю теневой контур..."
docker compose -f compose.shadow.yaml stop

echo
echo "Готово. Боевой шлюз кабинет не терял — shadow только читала."
echo
echo "Данные остались в томе shadow-postgres: отчёт расхождений за наблюдение"
echo "это единственное, ради чего шаг 2 делался. Удалять — только осознанно:"
echo "    docker compose -f compose.shadow.yaml down -v"
