-- Хранение считается от объёма товара, а не от числа занятых коробов.
-- Решение владельца 12.09.2026, раздел 13.
--
-- Единица тарифа осталась прежней — коробко-место × сутки, — но количество
-- теперь вычисляется:
--
--     коробо-места = Σ по штрихкодам ( остаток_единиц / units_per_box )
--
-- То есть «сколько места занял бы товар, если сложить его плотно», а не
-- «сколько коробов стоит на полке». Разницу — недобранные короба, пустоты,
-- неуплотнённые остатки — платим мы, и это осознанно: пустоты создаёт склад,
-- складу ими и управлять.
--
-- Почему норма, а не габариты. Габаритов вещи у нас нет: `dims_mm` пуст у всех
-- записей, в карточке Wildberries их тоже нет (контракт отдаёт `barcode`,
-- `seller_sku`, `name`, `nm_id`, `brand`, `subject`, `mapped`). А норма «сколько
-- этой вещи влезло в короб» снимается с приёмки сама: кладовщик разложил
-- тысячу футболок по коробам — система записала, сколько легло в каждый.
-- В этом числе уже сидит и объём вещи, и плотность укладки, и форма короба,
-- и оно измерено, а не выведено.
--
-- ВАЖНО, и записано в разделе 13 оговоркой: норма не лучше самого полного
-- короба, который когда-либо приезжал. Товар, приходящий пробными партиями по
-- десять штук, получит норму 10 — и клиент заплатит целое место за десять
-- футболок, хотя их влезает сорок четыре. Поэтому норма правится руками
-- (`/catalog/units-per-box`) и растёт сама при каждой более полной приёмке.

ALTER TABLE sku ADD COLUMN IF NOT EXISTS units_per_box integer;

-- NULL — нормы ещё нет, ни одной приёмки в короб не было. Ноль запрещён
-- отдельно: на него делят.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'sku_units_per_box_positive') THEN
        ALTER TABLE sku ADD CONSTRAINT sku_units_per_box_positive
            CHECK (units_per_box IS NULL OR units_per_box > 0);
    END IF;
END $$;

COMMENT ON COLUMN sku.units_per_box IS
    'Сколько единиц этой вещи входит в короб. Снимается с приёмки как максимум '
    'наблюдённого, правится руками. NULL — нормы ещё нет.';

-- `box.quantity` не пишет никто и никогда: настоящее количество лежит в
-- `stock_balance`, ключ которого включает `box_id`. Колонка всегда ноль и
-- выглядит при этом как ответ на вопрос «сколько в коробе» — первый же отчёт,
-- написанный по ней, даст нули, и никто их не перепроверит. Убрать её нельзя
-- задним числом (правило 9.5: миграции не переписываются), поэтому она
-- помечается словами.
COMMENT ON COLUMN box.quantity IS
    'НЕ ИСПОЛЬЗУЕТСЯ: всегда 0. Количество в коробе — stock_balance по box_id.';

-- Счёт хранения ходит по журналу за прошедшие сутки: остаток на конец дня
-- собирается из stock_move, а не из проекции. Проекция знает только «сейчас».
CREATE INDEX IF NOT EXISTS stock_move_owner_ts_idx ON stock_move (owner_id, ts);
