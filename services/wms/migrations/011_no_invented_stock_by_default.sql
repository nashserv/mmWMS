-- Остаток по умолчанию не выдумывается. Решение владельца 13.09.2026.
--
-- Было: `allow_ledger_short boolean NOT NULL DEFAULT true` (миграция 001).
-- То есть каждый заведённый клиент молча получал поведение боевого контура:
-- товара по учёту нет — резерв дописывается поверх, задание уезжает, книга
-- расходится с полкой. Ровно так боевой остаток стал 92 единицами на 21
-- продавца, и ровно поэтому `_force_reservation` никого не разбудил.
--
-- Умолчание — это то, что происходит, когда никто ничего не решал. «Придумать
-- остаток» не имеет права быть тем, что происходит само.
--
-- Признак того, что умолчание выбрано неверно, был на виду: в инструкции по
-- shadow (`infrastructure/shadow/README.md`, подшаг 3) ПЕРВЫМ ДЕЙСТВИЕМ стоит
-- «выключить клапан», иначе каждое теневое задание создаёт расхождение. Когда
-- первый шаг развёртывания — отключить умолчание, умолчание неправильное.
--
-- ЧТО ТЕПЕРЬ ПРОИСХОДИТ, когда товара по учёту нет.
--
-- Задание встаёт в `short`: видимое, счётное, с событием
-- `wms.reservation.failed.v1`. Оно НЕ исчезает в тихой отмене — тихих отмен в
-- боевом контуре 2645, и у всех `manual_review_reason = NULL`.
--
-- Возражение «смену нельзя останавливать» верное, но выбор был ложный.
-- Альтернатива дописке — не остановка, а ПЕРЕСЧЁТ ЯЧЕЙКИ: маршрут
-- `/inventory/count-cell` существует ровно для этого, считается одна ячейка у
-- стойки, результат уезжает движениями с `doc_type='inventory'`. Минута
-- работы — и книга сходится с полкой по-настоящему, а не поверх.
--
-- Клапан никуда не делся: `allow_ledger_short = true` по конкретному клиенту
-- остаётся правом владельца. Но теперь это решение, принятое вслух, а не
-- умолчание, о котором никто не знает.

ALTER TABLE owner ALTER COLUMN allow_ledger_short SET DEFAULT false;

COMMENT ON COLUMN owner.allow_ledger_short IS
    'Разрешено ли собирать поверх недостающего учётного остатка. По умолчанию '
    'НЕТ: задание встаёт в short, ячейка пересчитывается. Включается по '
    'клиенту решением владельца, и это решение оставляет след в журнале.';

-- Существующие клиенты переводятся тоже.
--
-- На стенде это синтетические продавцы. На бою миграция ложится ДО того, как
-- через новую WMS пройдёт первое задание (раздел 11, шаг 3 — начальный
-- остаток), поэтому никакая идущая смена от этого не встанет. Оставить старым
-- клиентам прежнее поведение значило бы развести две политики в одной базе, и
-- разница между ними всплыла бы расхождением, которого никто не ждал.
UPDATE owner SET allow_ledger_short = false WHERE allow_ledger_short;
