"""Подключение тестов к настоящему Postgres.

Транзакцию раздела 6.2 нельзя проверить на заглушке: её смысл — блокировки,
триггеры проекции и `ON CONFLICT`, то есть ровно то, чего в памяти нет.
Поэтому тесты ядра идут против живой базы с применёнными миграциями.

Адрес берётся из `WMS_TEST_DATABASE_URL` (или `DATABASE_URL`). Без него тесты
ядра не выполняются — и говорят об этом вслух, а не притворяются зелёными.

**На стенде это ОТДЕЛЬНАЯ база `wms_test`, а не рабочая `wms`.** Рядом с
рабочей крутятся настоящие воркеры: опрос Wildberries, стикеры, сверка. Против
общей базы тест и воркер разбирают одни и те же задания, и тест краснеет
«опросчик завёл 3 из 5», хотя сломан не он. Хуже другое: каждый прогон
оставляет в базе своего продавца и свой кабинет WB, опросчик берёт по восемь
кабинетов за тик — и через несколько сотен прогонов полный круг перестаёт
укладываться в две секунды, из-за чего краснеет уже полный прогон.

В CI такой заботы не нужно: там Postgres поднимается на прогон, воркеров нет.
"""
from __future__ import annotations

import os
import uuid

import pytest

REQUIRED = (
    "нужен Postgres с применёнными миграциями: задайте WMS_TEST_DATABASE_URL. "
    "Транзакция 6.2 проверяется блокировками и триггерами, на заглушке её нет."
)

# Имя базы обязано оканчиваться на `_test`. Это не вкусовщина: фолбэк на
# DATABASE_URL уже стоил стенду 957 чужих владельцев `utest-*` из 997 и 85
# отрицательных остатков. Тесты заводят продавцов, кабинеты и станции пачками —
# в рабочей базе им не место, и опросчик, который берёт по восемь кабинетов за
# такт, на девятистах перестаёт укладываться в две секунды.
_TEST_SUFFIX = "_test"


def _database_name(dsn: str) -> str:
    from urllib.parse import urlparse

    return (urlparse(dsn).path or "").lstrip("/").split("?")[0]


def database_url() -> str | None:
    """Адрес ТЕСТОВОЙ базы. Фолбэка на DATABASE_URL здесь нет намеренно.

    Он был, и молча уводил тесты в рабочую базу, когда переменную забывали
    задать. Забыть — это норма; уронить из-за этого стенд — нет.
    """
    return (os.getenv("WMS_TEST_DATABASE_URL") or "").strip() or None


def require_database() -> str:
    url = database_url()
    if not url:
        pytest.skip(REQUIRED)
    name = _database_name(url)
    if not name.endswith(_TEST_SUFFIX):
        # Не skip и не fail отдельного теста: продолжать нельзя вообще, иначе
        # следующий же тест начнёт писать в рабочую базу.
        pytest.exit(
            f"WMS_TEST_DATABASE_URL указывает на базу {name!r}, а имя обязано "
            f"оканчиваться на {_TEST_SUFFIX!r}. Юнит-тесты заводят продавцов и "
            f"кабинеты пачками — в рабочей базе им не место: так уже натекло "
            f"957 владельцев utest-* и опросчик перестал укладываться в бюджет. "
            f"Поднимите wms_test (сервис wms-test-migrate в compose стенда).",
            returncode=2)
    return url


def unique(prefix: str) -> str:
    """Идентификатор, не сталкивающийся ни с сидом стенда, ни с прошлым прогоном.

    База стенда не пустая — в ней 22 продавца и 255 SKU из реальной выгрузки.
    Тест обязан работать рядом с ними, а не требовать чистой базы: именно так
    сервис и будет жить.
    """
    return f"utest-{prefix}-{uuid.uuid4().hex[:12]}"
